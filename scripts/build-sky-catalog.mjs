#!/usr/bin/env node
/**
 * Builds src/data/skyCatalog.ts from the d3-celestial data files
 * (https://github.com/ofrohn/d3-celestial, BSD-3-Clause, © Olaf Frohn).
 *
 *   npm pack d3-celestial && tar xzf d3-celestial-*.tgz
 *   node scripts/build-sky-catalog.mjs package/data
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const MAG_LIMIT = 5.5;
// Octans trapezoid stars fainter than the limit, kept so the southern asterism is complete.
const ALWAYS_INCLUDE = new Set([111196 /* υ Oct, mag 5.76 */]);
const PROPER_NAME_MAG = 3.5; // proper names only for stars bright enough to recognise

const dataDir = process.argv[2];
if (!dataDir) {
  console.error('usage: node scripts/build-sky-catalog.mjs <d3-celestial data dir>');
  process.exit(1);
}
const read = (f) => JSON.parse(readFileSync(join(dataDir, f), 'utf8'));
const stars = read('stars.6.json').features;
const names = read('starnames.json');
const lines = read('constellations.lines.json').features;
const constellations = read('constellations.json').features;

const ra = (lon) => +(((lon % 360) + 360) % 360).toFixed(3);
const dec = (lat) => +lat.toFixed(3);

const kept = stars
  .filter((s) => s.properties.mag <= MAG_LIMIT || ALWAYS_INCLUDE.has(s.id))
  .sort((a, b) => a.properties.mag - b.properties.mag);

const starData = [];
const properNames = {};
const designations = {};
kept.forEach((s, i) => {
  const [lon, lat] = s.geometry.coordinates;
  starData.push(ra(lon), dec(lat), +s.properties.mag.toFixed(2));
  const n = names[String(s.id)];
  if (!n) return;
  if (n.name && s.properties.mag <= PROPER_NAME_MAG) properNames[i] = n.name;
  const desig = n.bayer || n.flam;
  if (desig && n.c) designations[i] = `${desig} ${n.c}`;
});

const consts = constellations.map((c) => {
  const segments = lines.find((l) => l.id === c.id)?.geometry.coordinates ?? [];
  return {
    id: c.id,
    name: c.properties.name,
    label: [ra(c.geometry.coordinates[0]), dec(c.geometry.coordinates[1])],
    lines: segments.map((seg) => seg.flatMap(([lon, lat]) => [ra(lon), dec(lat)])),
  };
});

const out = `// Generated by scripts/build-sky-catalog.mjs — do not edit by hand.
// Star positions, names and constellation figures from d3-celestial
// (https://github.com/ofrohn/d3-celestial), BSD-3-Clause, © 2015 Olaf Frohn.
// Coordinates are J2000 RA/Dec in degrees; stars are sorted brightest first.

/** Flat [raDeg, decDeg, mag, …] for ${kept.length} stars down to magnitude ${MAG_LIMIT}. */
export const STAR_DATA: readonly number[] = ${JSON.stringify(starData)};

/** Proper names (magnitude ≤ ${PROPER_NAME_MAG}), keyed by star index. */
export const STAR_NAMES: Readonly<Record<number, string>> = ${JSON.stringify(properNames)};

/** Bayer / Flamsteed designations such as "σ Oct", keyed by star index. */
export const STAR_DESIGNATIONS: Readonly<Record<number, string>> = ${JSON.stringify(designations)};

export interface ConstellationFigure {
  id: string;
  name: string;
  /** Label position [raDeg, decDeg]. */
  label: readonly [number, number];
  /** Polylines, each a flat [raDeg, decDeg, …] list. */
  lines: readonly (readonly number[])[];
}

export const CONSTELLATIONS: readonly ConstellationFigure[] = ${JSON.stringify(consts)};
`;

const target = new URL('../src/data/skyCatalog.ts', import.meta.url);
writeFileSync(target, out);
console.log(`stars ${kept.length}, names ${Object.keys(properNames).length}, constellations ${consts.length}, ${out.length} bytes`);
